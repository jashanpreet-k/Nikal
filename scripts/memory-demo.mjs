import { mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';
import assert from 'node:assert/strict';
const directory = mkdtempSync(join(tmpdir(), 'nikal-memory-demo-'));
const env = { ...process.env, NIKAL_DATA_DIR: directory, NIKAL_LAT: '', NIKAL_LON: '' };
const run = (...args) => execFileSync(process.execPath, ['dist/cli.js', ...args], { env, encoding: 'utf8' });
console.log('OFFLINE FIXTURE: synthetic forecast and places; deterministic fallback; three separate CLI processes.');
console.log('\nRun 1: nikal --fixture --no-model');
const before = JSON.parse(run('--fixture', '--no-model', '--json'));
console.log(before.card);
console.log('\nSave: "I dislike heat above 30°C and prefer mornings."');
console.log(run('prefs', 'set', '--max-temp', '30', '--period', 'morning'));
console.log('Run 2: a NEW nikal --fixture --no-model process reads the saved memory');
const after = JSON.parse(run('--fixture', '--no-model', '--json'));
console.log(after.card);
assert.equal(after.context.preferences.maxTemp, 30);
assert.equal(after.context.preferences.period, 'morning');
assert.notEqual(before.context.decision.timeId, after.context.decision.timeId);
assert(after.context.candidates.every(hour => hour.temperature <= 30));
console.log(`\nPASS: preference retrieved across processes; chosen time changed. Isolated demo SQLite: ${directory}/memory.db`);
